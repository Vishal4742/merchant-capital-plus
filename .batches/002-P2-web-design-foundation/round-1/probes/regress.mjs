// Batch 001 regression on the restyled page: keyboard "Read block again" keeps focus and re-reads via Nym; hover styles.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("/Users/vg890/.npm/_npx/e41f203b7505f1fb/node_modules/playwright");
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const reqs = [];
context.on("request", (r) => reqs.push(r.url()));
const page = await context.newPage();
const lines = [];
page.on("pageerror", (e) => lines.push(`pageerror: ${e.message.slice(0, 160)}`));
await page.goto("http://localhost:3100/");
const chain = page.locator("section", { hasText: "Private chain read" }).last();
const pill = chain.locator("span.rounded-pill").first();
await page.waitForFunction((el) => /OK|Failed/.test(el.textContent), await pill.elementHandle(), { timeout: 300000, polling: 250 });
const first = { pill: await pill.textContent(), text: (await chain.locator("p").textContent()).trim() };
const btn = chain.getByRole("button", { name: "Read block again" });
const hover = async (loc) => { await loc.hover(); await page.waitForTimeout(400); return loc.evaluate((b) => { const cs = getComputedStyle(b); return { translate: cs.translate, boxShadow: cs.boxShadow.slice(0, 60), bg: cs.backgroundColor, color: cs.color }; }); };
const quietHover = await hover(btn);
const holdHover = await hover(page.getByRole("button", { name: "Hold to sign again" }));
await page.mouse.move(5, 5);
await btn.focus();
await page.keyboard.press("Enter");
await page.waitForTimeout(150);
const during = await page.evaluate(() => { const a = document.activeElement; return { focus: a.textContent, ariaDisabled: a.getAttribute("aria-disabled"), opacity: getComputedStyle(a).opacity, translateOnHover: null }; });
const duringPill = await pill.textContent();
await btn.hover(); await page.waitForTimeout(400);
during.hoverWhileDisabled = await btn.evaluate((b) => getComputedStyle(b).translate);
await page.waitForFunction((el) => /OK|Failed/.test(el.textContent), await pill.elementHandle(), { timeout: 300000, polling: 250 });
const second = { pill: await pill.textContent(), text: (await chain.locator("p").textContent()).trim(), focus: await page.evaluate(() => document.activeElement.textContent) };
console.log(JSON.stringify({ first, quietHover, holdHover, during, duringPill, second, ankr: reqs.filter((u) => u.includes("rpc.ankr.com")).length, gfonts: reqs.filter((u) => /fonts\.(googleapis|gstatic)/.test(u)).length, errors: lines }, null, 1));
await browser.close();
