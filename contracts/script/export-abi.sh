#!/usr/bin/env bash
# Regenerates packages/shared/contracts.ts: ABIs of the four Phase 3 contracts (from `forge inspect`, so never a stale
# build) and their 1874 addresses from the DeployPhase3 record. Writes to a temp file and moves it into place, so a
# failure never leaves a half-written or empty file. Usage (repo root): bash contracts/script/export-abi.sh
set -euo pipefail
cd "$(dirname "$0")/../.."
export PATH="$HOME/.foundry/bin:$PATH"
out=packages/shared/contracts.ts
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
abis=$(mktemp -d)
for c in MerchantPay CapitalMarket ClaimToken InvestorRegistry; do
  (cd contracts && forge inspect "src/$c.sol:$c" abi --json) > "$abis/$c.json"
done
record=contracts/broadcast/DeployPhase3.s.sol/1874/run-latest.json
python3 -I - "$abis" "$record" > "$tmp" <<'PY'
import json, pathlib, sys
abis, record = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
names = ["MerchantPay", "CapitalMarket", "ClaimToken", "InvestorRegistry"]
addr = {n: None for n in names}
if record.exists():
    for t in json.loads(record.read_text())["transactions"]:
        if t.get("transactionType") == "CREATE" and t.get("contractName") in addr:
            addr[t["contractName"]] = t["contractAddress"]
def lit(a):
    return f'"{a}"' if a else "null"
lower = lambda n: n[0].lower() + n[1:]
print("""// GENERATED by contracts/script/export-abi.sh from `forge inspect` and the DeployPhase3 record. Do not edit.
// Whiteflow on Whitechain Sepolia (chain 1874). ABI frozen at gate G3 (batch 005-P3-advance).
// No imports and no dependencies: viem users pass these objects straight to its functions.

export const chainId = 1874 as const;
""")
print("export const addresses = {")
print('  usdt: "0xcedfB56113143d55b2358b8CFbB0dEB5Ad2f55a7",')
for n in names:
    print(f"  {lower(n)}: {lit(addr[n])},")
print("} as const;\n")
print("""export const KIND_INVOICE = 1 as const; // MerchantPay nonce kinds
export const KIND_SALE = 2 as const;
export const OFFER_INVOICE = 1 as const; // CapitalMarket offer kinds
export const OFFER_ADVANCE = 2 as const;
export const MIN_PAYMENT = 1_000_000n; // 1 USDT (6 decimals)
export const MAX_FEE = 250_000n; // 0.25 USDT
export const LOCK_WINDOW_SECONDS = 60; // testnet

/** EIP-712 domain of the prize USDT; equals its on-chain DOMAIN_SEPARATOR() (pinned by a fork test). */
export const usdtDomain = {
  name: "Tether USD",
  version: "1",
  chainId: 1874,
  verifyingContract: "0xcedfB56113143d55b2358b8CFbB0dEB5Ad2f55a7",
} as const;

/**
 * Every payer signs this, `to` = the contract that pulls:
 * - sale: to = merchantPay, value = the sale price (the 0.10 fee comes out of it)
 * - invoice: to = merchantPay, value = the credited amount + relayFee (fee on top), nonce bound to the credited amount
 * - funding: to = capitalMarket, value = capitalMarket.quote(claimId, units), nonce = fundingNonce(claimId, investor, units, salt)
 */
export const receiveWithAuthorizationTypes = {
  ReceiveWithAuthorization: [
    { name: "from", type: "address" },
    { name: "to", type: "address" },
    { name: "value", type: "uint256" },
    { name: "validAfter", type: "uint256" },
    { name: "validBefore", type: "uint256" },
    { name: "nonce", type: "bytes32" },
  ],
} as const;

/**
 * MerchantPay nonce = keccak256(encodeAbiParameters(nonceParams, [1874n, merchantPay, kind, ref, orderRef, amount, salt]))
 * sale: kind = KIND_SALE, ref = BigInt(merchant), orderRef = the checkout's random 32 bytes, amount = the price
 * invoice: kind = KIND_INVOICE, ref = invoiceId, orderRef = 0x00…00, amount = the credited amount (without the fee)
 * Check it against MerchantPay.saleNonce / invoiceNonce; for funding use CapitalMarket.fundingNonce.
 */
export const nonceParams = [
  { name: "chainId", type: "uint256" },
  { name: "merchantPay", type: "address" },
  { name: "kind", type: "uint8" },
  { name: "ref", type: "uint256" },
  { name: "orderRef", type: "bytes32" },
  { name: "amount", type: "uint256" },
  { name: "salt", type: "bytes32" },
] as const;
""")
for n in names:
    abi = json.loads((abis / f"{n}.json").read_text())
    print(f"export const {lower(n)}Abi = {json.dumps(abi, indent=2)} as const;\n")
PY
mkdir -p packages/shared
mv "$tmp" "$out"
trap - EXIT
rm -rf "$abis"
echo "wrote $out ($(grep -c '' "$out") lines)"
