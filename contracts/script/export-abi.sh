#!/usr/bin/env bash
# Regenerates packages/shared/merchantPay.ts from the forge build and the latest 1874 deploy record.
# Usage (repo root): bash contracts/script/export-abi.sh   (run `forge build` in contracts/ first)
set -euo pipefail
cd "$(dirname "$0")/../.."
export PATH="$HOME/.foundry/bin:$PATH"

record=contracts/broadcast/DeployMerchantPay.s.sol/1874/run-latest.json
addr=$(python3 -I -c '
import json, sys, pathlib
p = pathlib.Path(sys.argv[1])
txs = json.loads(p.read_text())["transactions"] if p.exists() else []
print(next((t["contractAddress"] for t in txs if t.get("contractName") == "MerchantPay" and t.get("transactionType") == "CREATE"), ""))' "$record")
[ -n "$addr" ] && addr=$(cast to-check-sum-address "$addr")

mkdir -p packages/shared
python3 -I - "$addr" > packages/shared/merchantPay.ts <<'PY'
import json, sys
addr = sys.argv[1]
abi = json.load(open("contracts/out/MerchantPay.sol/MerchantPay.json"))["abi"]
mp = f'"{addr}"' if addr else "null"
print(f"""// GENERATED by contracts/script/export-abi.sh from the forge build. Do not edit by hand.
// MerchantPay on Whitechain Sepolia (chain 1874), batch 002-P2-merchantpay. The ABI freezes at gate G3.
// No imports and no dependencies: viem users pass these objects straight to its functions.

export const chainId = 1874 as const;

export const addresses = {{
  usdt: "0xcedfB56113143d55b2358b8CFbB0dEB5Ad2f55a7",
  merchantPay: {mp},
}} as const;

export const KIND_INVOICE = 1 as const;
export const KIND_SALE = 2 as const;
export const MIN_PAYMENT = 1_000_000n; // 1 USDT (6 decimals)
export const MAX_FEE = 250_000n; // 0.25 USDT

/** EIP-712 domain of the prize USDT; equals its on-chain DOMAIN_SEPARATOR() (pinned by a fork test). */
export const usdtDomain = {{
  name: "Tether USD",
  version: "1",
  chainId: 1874,
  verifyingContract: "0xcedfB56113143d55b2358b8CFbB0dEB5Ad2f55a7",
}} as const;

/** The payer signs this with `to` = addresses.merchantPay and `value` = the gross amount. */
export const receiveWithAuthorizationTypes = {{
  ReceiveWithAuthorization: [
    {{ name: "from", type: "address" }},
    {{ name: "to", type: "address" }},
    {{ name: "value", type: "uint256" }},
    {{ name: "validAfter", type: "uint256" }},
    {{ name: "validBefore", type: "uint256" }},
    {{ name: "nonce", type: "bytes32" }},
  ],
}} as const;

/**
 * nonce = keccak256(encodeAbiParameters(nonceParams, [1874n, merchantPay, kind, ref, orderRef, amount, salt]))
 * sale: kind = KIND_SALE, ref = BigInt(merchant), orderRef = the checkout's random 32 bytes
 * invoice: kind = KIND_INVOICE, ref = invoiceId, orderRef = 0x00…00
 * Check it against MerchantPay.saleNonce / invoiceNonce.
 */
export const nonceParams = [
  {{ name: "chainId", type: "uint256" }},
  {{ name: "merchantPay", type: "address" }},
  {{ name: "kind", type: "uint8" }},
  {{ name: "ref", type: "uint256" }},
  {{ name: "orderRef", type: "bytes32" }},
  {{ name: "amount", type: "uint256" }},
  {{ name: "salt", type: "bytes32" }},
] as const;

export const merchantPayAbi = {json.dumps(abi, indent=2)} as const;""")
PY
echo "wrote packages/shared/merchantPay.ts (merchantPay: ${addr:-not deployed})"
